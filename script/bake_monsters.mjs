// Writes the locked monster atlases the browser loads instead of baking them.
//   node script/bake_monsters.mjs          write the PNGs and the sheet table
// js/monster_bake.test.js fails when the committed files drift from the code.
import { mkdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { sheetMeta, writeAtlasPng } from "../assets/js/monster_bake.js"
import { bakeMonster, monsterKinds } from "../assets/js/monsters.js"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const out = join(root, "priv/static/images/hd2d/monsters")
mkdirSync(out, { recursive: true })
const table = {}
for (const kind of monsterKinds()) {
  const parts = bakeMonster(kind)
  const card = parts[0]
  const png = writeAtlasPng(card.atlas, card.atlasW, card.atlasH)
  writeFileSync(join(out, `${kind}.png`), png)
  table[kind] = sheetMeta(parts)
  console.log(`${kind} ${card.atlasW}x${card.atlasH} ${png.length} bytes`)
}
writeFileSync(
  join(root, "assets/js/monster-sheets.js"),
  "// Generated by script/bake_monsters.mjs. Do not edit.\n" + `export const monsterSheets = ${JSON.stringify(table, null, 2)}\n`
)
